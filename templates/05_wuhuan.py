import turtle
turtle.width(10)#设置画笔宽度10
turtle.color("blue")#设置画笔颜色为蓝色
turtle.circle(50)#画一个半径为50的圆

turtle.penup()#抬起画笔，准备移动
turtle.goto(120,0)#移动到坐标(80,0)
turtle.pendown()#放下画笔
turtle.color("black")#设置画笔颜色为黑色
turtle.circle(50)#画一个半径为50的圆

turtle.penup()#抬起画笔，准备移动 
turtle.goto(240,0)#移动到坐标(0,160)
turtle.pendown()#放下画笔   
turtle.color("red")#设置画笔颜色为红色
turtle.circle(50)#画一个半径为50的圆

turtle.penup()#抬起画笔，准备移动 
turtle.goto(65,-55)#移动到坐标(40,-60)
turtle.pendown()#放下画笔   
turtle.color("yellow")#设置画笔颜色为黄色
turtle.circle(50)#画一个半径为50的圆

turtle.penup()#抬起画笔，准备移动
turtle.goto(185,-55)#移动到坐标(120,-60)
turtle.pendown()#放下画笔
turtle.color("green")#设置画笔颜色为绿色
turtle.circle(50)#画一个半径为50的圆










turtle.done()#完成绘画，保持窗口打开