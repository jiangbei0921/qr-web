import turtle
turtle.showturtle()
turtle.write("Hello, World!")
turtle.forward(300)#向前行走300像素
turtle.color("red")#设置画笔颜色为红色
turtle.left(90)#向左转90度  
turtle.forward(300)#向前行走300像素
turtle.goto(0,50)#移动到坐标(0,50)
turtle.goto(0,0)#移动到坐标(0,0)
turtle.penup()#抬起画笔
turtle.goto(0,300)#移动到坐标(0,300)
turtle.pendown()#放下画笔
turtle.circle(100)#画一个半径为100像素的圆\
turtle.done()#结束绘图，保持窗口打开